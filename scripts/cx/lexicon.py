"""요양병원 VOC 도메인 감정 룰 사전 (해석·정당화 가능 / BERT 대체).

룰 기반 사전을 쓰는 이유: 일반 한국어 감정모델은 요양 도메인에 약하고,
발표 자리에서 '왜 이 단어가 부정인가'를 한 단어씩 정당화할 수 있어야 하기 때문.
부정어/긍정어는 어간(접두) 매칭으로 활용형까지 포착한다.
"""

# 부정 감정어 (어간 매칭). 요양병원 페인 도메인 특화.
NEGATIVE = [
    "힘들", "힘듦", "부담", "불안", "걱정", "짜증", "냄새", "학대", "폐업", "이직",
    "인력부족", "부족", "사망", "집단감염", "위험", "처분", "환수", "소송", "민원",
    "불신", "야간", "과로", "번아웃", "퇴사", "그만두", "열악", "더럽", "방치",
    "욕창", "고통", "어렵", "최악", "스트레스", "갑질", "감염", "확진", "격리",
]

# 긍정 감정어 (어간 매칭).
POSITIVE = [
    "안심", "편하", "깨끗", "청결", "만족", "추천", "개선", "안전", "신뢰", "친절",
    "쾌적", "편리", "도움", "회복", "감사", "좋아",
]

# 노이즈(도메인 무관) 필터 패턴 — 포함 시 문서 제거.
NOISE = [
    "장례", "장례식장", "학원", "분양", "부동산", "결막염", "동물병원", "반려동물",
    "맛집", "할인", "이벤트", "쿠폰", "적금", "대출", "코인", "주식", "채용공고",
]

def count_hits(text: str, words) -> int:
    return sum(1 for w in words if w in text)

def is_negative(text: str) -> bool:
    return count_hits(text, NEGATIVE) >= 1

def is_positive(text: str) -> bool:
    return count_hits(text, POSITIVE) >= 1

def is_noise(text: str) -> bool:
    return any(n in text for n in NOISE)
